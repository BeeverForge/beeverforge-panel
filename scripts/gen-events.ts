// Generates src/api/generated/events.ts from the core's committed description of every frame the
// streams send (its docs/reference/events.schema.json, copied into contract/ at contract/core-ref). Each `*Data` definition is the shape
// of one frame as it travels today; the envelope types describe the planned single stream.
import { readFile, writeFile, mkdir } from "node:fs/promises";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { compile, type JSONSchema } from "json-schema-to-typescript";

const here = dirname(fileURLToPath(import.meta.url));
const source = resolve(here, "../contract/events.schema.json");
const target = resolve(here, "../src/api/generated/events.ts");

const schema = JSON.parse(await readFile(source, "utf8")) as JSONSchema & {
  $defs: Record<string, JSONSchema>;
};

// json-schema-to-typescript reads `definitions`; the file uses draft 2020-12's `$defs`.
const rewritten = JSON.parse(
  JSON.stringify(schema).replaceAll("#/$defs/", "#/definitions/"),
) as JSONSchema & { $defs?: Record<string, JSONSchema> };
rewritten.definitions = rewritten.$defs;
delete rewritten.$defs;
delete (rewritten as { discriminator?: unknown }).discriminator;

const body = await compile(rewritten, "StreamEvent", {
  bannerComment:
    "/* Generated by scripts/gen-events.ts from contract/events.schema.json (the core's docs/reference/events.schema.json at contract/core-ref). Do not edit. */",
  additionalProperties: true,
  unreachableDefinitions: true,
  strictIndexSignatures: false,
  format: false,
});

await mkdir(dirname(target), { recursive: true });
await writeFile(target, body);
console.log(`wrote ${target}`);
